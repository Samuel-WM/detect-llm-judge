"""Section 4.2: two independent samples from pi_ref per prompt, T=1.0, top_p=0.95,
max_new_tokens=256, max_prompt_tokens=384. Response pairs are sampled from pi_ref, not pi_A --
the estimand requires it. Checkpointed: resumable, skips prompts already generated.

Batched generation, length-bucketed (batch_size=64): single-sequence batch_size=1 generation on
this GPU/Windows measured at ~7-9 tok/s (WDDM per-kernel-launch overhead dominates at this model
size, not compute or memory bandwidth) -- batching amortizes that overhead across the batch
dimension and gets ~520-625 aggregate tok/s at batch 64-128, confirmed empirically before
committing to this design (see RESULTS.md). Left-padding + bucketing by tokenized prompt length
(per PHASE_0C_SPEC.md's closing note on allocator fragmentation) keeps padding waste low.

Run: .venv/Scripts/python.exe -m src.gen.sample_pairs --prompts probe --n 600
"""
import argparse
import json
import os

os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")

import time
from pathlib import Path

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

from src.common.vram import free_vram_gb, reclaim
from src.data.build_prompts import build_prompt_splits, load_cfg
from tests.test_templating import run as run_templating_check

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
CACHE_DIR = REPO_ROOT / "data_cache"
BATCH_SIZE = 64


def build_chat_texts(tokenizer, prompts: list[str]) -> list[str]:
    return [
        tokenizer.apply_chat_template(
            [{"role": "user", "content": p}], add_generation_prompt=True, tokenize=False,
        )
        for p in prompts
    ]


def length_bucketed_batches(tokenizer, prompts: list[str], batch_size: int) -> list[list[int]]:
    """Returns lists of prompt indices, sorted by tokenized length and chunked into batches --
    keeps padding waste low within each batch (adjacent-length prompts batched together).
    """
    lengths = [len(tokenizer.encode(p)) for p in prompts]
    order = sorted(range(len(prompts)), key=lambda i: lengths[i])
    return [order[i:i + batch_size] for i in range(0, len(order), batch_size)]


def generate_one_pass(model, tokenizer, prompts: list[str], cfg: dict, device: str) -> list[str]:
    gen_cfg = cfg["data"]["generation"]
    batches = length_bucketed_batches(tokenizer, prompts, BATCH_SIZE)
    results = [None] * len(prompts)

    for batch_idx_list in batches:
        batch_prompts = [prompts[i] for i in batch_idx_list]
        texts = build_chat_texts(tokenizer, batch_prompts)
        enc = tokenizer(
            texts, return_tensors="pt", padding=True, truncation=True,
            max_length=gen_cfg["max_prompt_tokens"], add_special_tokens=False,
        ).to(device)

        with torch.no_grad():
            out = model.generate(
                **enc, max_new_tokens=gen_cfg["max_new_tokens"], do_sample=True,
                temperature=gen_cfg["temperature"], top_p=gen_cfg["top_p"],
                pad_token_id=tokenizer.pad_token_id,
            )
        new_tokens = out[:, enc["input_ids"].shape[1]:]
        texts_out = tokenizer.batch_decode(new_tokens, skip_special_tokens=True)
        for local_idx, global_idx in enumerate(batch_idx_list):
            results[global_idx] = texts_out[local_idx]

    return results


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--prompts", choices=["train", "probe"], required=True)
    parser.add_argument("--n", type=int, default=None)
    # ROUND 5 4.2: the fresh final attribution holdout is drawn from the SAME prompt pool and
    # generated by the SAME procedure, but from a disjoint slice and into its own file so the
    # frozen calibration data is never mutated. Neither flag touches temperature, top_p,
    # max_new_tokens, the chat template, or the sampling policy.
    parser.add_argument("--slice-start", type=int, default=0)
    parser.add_argument("--tag", default=None)
    args = parser.parse_args()

    cfg = load_cfg()
    run_templating_check(cfg["models"]["base_policy"])
    splits = build_prompt_splits(cfg, cfg["seed"])
    prompts = splits[f"{args.prompts}_prompts"]
    prompts = prompts[args.slice_start:]
    if args.n is not None:
        prompts = prompts[:args.n]

    suffix = f"_{args.tag}" if args.tag else ""
    out_path = CACHE_DIR / f"response_pairs_{args.prompts}{suffix}.jsonl"
    done_prompts = set()
    if out_path.exists():
        with open(out_path) as f:
            for line in f:
                done_prompts.add(json.loads(line)["prompt"])
        print(f"resuming: {len(done_prompts)} prompts already have pairs")

    remaining = [p for p in prompts if p not in done_prompts]
    if not remaining:
        print("nothing to do, all requested prompts already generated")
        return
    print(f"generating {len(remaining)} remaining prompts, batch_size={BATCH_SIZE}")

    baseline_vram = free_vram_gb()
    tokenizer = AutoTokenizer.from_pretrained(cfg["models"]["base_policy"])
    tokenizer.padding_side = "left"
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    model = AutoModelForCausalLM.from_pretrained(
        cfg["models"]["base_policy"], dtype=torch.bfloat16, attn_implementation="sdpa",
    ).to("cuda")
    model.eval()

    t0 = time.time()
    pass_a_checkpoint = CACHE_DIR / f"response_pairs_{args.prompts}{suffix}_passA.json"
    if pass_a_checkpoint.exists():
        with open(pass_a_checkpoint) as f:
            checkpoint = json.load(f)
        if checkpoint["prompts"] == remaining:
            responses_a = checkpoint["responses"]
            print(f"  pass A resumed from checkpoint, {time.time()-t0:.1f}s elapsed")
        else:
            responses_a = None
    else:
        responses_a = None
    if responses_a is None:
        responses_a = generate_one_pass(model, tokenizer, remaining, cfg, "cuda")
        with open(pass_a_checkpoint, "w") as f:
            json.dump({"prompts": remaining, "responses": responses_a}, f)
        print(f"  pass A done, {time.time()-t0:.1f}s elapsed")

    responses_b = generate_one_pass(model, tokenizer, remaining, cfg, "cuda")
    print(f"  pass B done, {time.time()-t0:.1f}s elapsed")

    with open(out_path, "a") as f:
        for prompt, ra, rb in zip(remaining, responses_a, responses_b):
            f.write(json.dumps({"prompt": prompt, "response_a": ra, "response_b": rb}) + "\n")
    pass_a_checkpoint.unlink(missing_ok=True)

    del model
    baseline_after = reclaim()
    print(f"generated {len(remaining)} new pairs in {time.time()-t0:.1f}s -> {out_path}")
    print(f"VRAM baseline={baseline_vram:.3f}GB after_cleanup={baseline_after:.3f}GB")


if __name__ == "__main__":
    main()
